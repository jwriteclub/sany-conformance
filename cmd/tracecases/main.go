// Command tracecases looks for the corpus file a generated case came from, by content.
// libFuzzer records no parent, so this is the only trace available for a fuzz output,
// and it is evidence, not proof. For each query it reports the longest run of bytes it
// shares with any corpus file and the corpus file that covers most of it by runs of at
// least -k bytes. White space and module header and footer lines do not count in either.
//
//	tracecases -cases cases.jsonl -out trace.tsv [-k 16]
//
// Each input line is {"id","dir","files","corpus":bool,"query":bool}.
package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"index/suffixarray"
	"os"
	"path/filepath"
	"regexp"
	"sort"
)

type item struct {
	ID     string   `json:"id"`
	Dir    string   `json:"dir"`
	Files  []string `json:"files"`
	Corpus bool     `json:"corpus"`
	Query  bool     `json:"query"`
}

var boiler = regexp.MustCompile(`(?m)^[ \t]*(-{4,}[ \t]*MODULE[ \t]+\w+[ \t]*-{4,}|={4,})[ \t]*\r?$`)

// measured marks the bytes that count: not whitespace, not a module header or footer.
func measured(b []byte) []bool {
	m := make([]bool, len(b))
	for i, c := range b {
		m[i] = c != ' ' && c != '\t' && c != '\n' && c != '\r'
	}
	for _, loc := range boiler.FindAllIndex(b, -1) {
		for i := loc[0]; i < loc[1]; i++ {
			m[i] = false
		}
	}
	return m
}

func coverage(q, doc []byte, keep []bool, k int) (covered int) {
	mark := make([]bool, len(q))
	for i := 0; i+k <= len(q); i++ {
		if bytes.Contains(doc, q[i:i+k]) {
			for j := i; j < i+k; j++ {
				mark[j] = true
			}
		}
	}
	for i := range q {
		if mark[i] && keep[i] {
			covered++
		}
	}
	return covered
}

func main() {
	cases := flag.String("cases", "", "input JSON lines")
	out := flag.String("out", "", "output TSV")
	k := flag.Int("k", 16, "shortest run of bytes that counts")
	flag.Parse()
	if err := run(*cases, *out, *k); err != nil {
		fmt.Fprintln(os.Stderr, "tracecases:", err)
		os.Exit(2)
	}
}

func run(cases, out string, k int) error {
	f, err := os.Open(cases)
	if err != nil {
		return err
	}
	defer f.Close()
	var items []item
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 0, 1<<20), 1<<24)
	for sc.Scan() {
		var it item
		if err := json.Unmarshal(sc.Bytes(), &it); err != nil {
			return err
		}
		items = append(items, it)
	}
	if err := sc.Err(); err != nil {
		return err
	}
	sort.Slice(items, func(i, j int) bool { return items[i].ID < items[j].ID })
	// The corpus, one copy per distinct file, with every case that holds it.
	var all bytes.Buffer
	type doc struct {
		start, end int
		owners     []string
	}
	var docs []*doc
	seen := map[string]*doc{}
	for _, it := range items {
		if !it.Corpus {
			continue
		}
		for _, n := range it.Files {
			b, err := os.ReadFile(filepath.Join(it.Dir, n))
			if err != nil {
				return err
			}
			if d := seen[string(b)]; d != nil {
				d.owners = append(d.owners, it.ID)
				continue
			}
			d := &doc{start: all.Len(), owners: []string{it.ID}}
			all.Write(b)
			all.WriteByte(0)
			d.end = all.Len() - 1
			seen[string(b)] = d
			docs = append(docs, d)
		}
	}
	text := all.Bytes()
	starts := make([]int, len(docs))
	for i, d := range docs {
		starts[i] = d.start
	}
	docAt := func(pos int) int { return sort.SearchInts(starts, pos+1) - 1 }
	fmt.Fprintf(os.Stderr, "corpus: %d files, %d bytes\n", len(docs), len(text))
	sa := suffixarray.New(text)
	w, err := os.Create(out)
	if err != nil {
		return err
	}
	defer w.Close()
	bw := bufio.NewWriter(w)
	defer bw.Flush()
	fmt.Fprintf(bw, "# Copyright 2026 Christopher O'Connell\n# SPDX-License-Identifier: Apache-2.0\n# Generated by cmd/tracecases. Evidence from content, not proof of ancestry.\nid\tbytes\tmeasured\tlongest_run\tbest_parent\tcovered\tcovered_pct\tother_files_tied\n")
	for _, it := range items {
		if !it.Query {
			continue
		}
		var q []byte
		for _, n := range it.Files {
			b, err := os.ReadFile(filepath.Join(it.Dir, n))
			if err != nil {
				return err
			}
			q = append(q, b...)
			q = append(q, 0)
		}
		keep := measured(q)
		total := 0
		for _, v := range keep {
			if v {
				total++
			}
		}
		// Greedy longest matches, left to right; every file holding one gets credit.
		credit := map[int]int{}
		longest := 0
		for i := 0; i+k <= len(q); {
			lo, hi := k, len(q)-i
			if bytes.IndexByte(q[i:i+k], 0) >= 0 || !hasAny(sa, q[i:i+k]) {
				i++
				continue
			}
			// Exponential then binary search for the longest prefix present.
			for lo < hi {
				mid := (lo + hi + 1) / 2
				if bytes.IndexByte(q[i:i+mid], 0) < 0 && hasAny(sa, q[i:i+mid]) {
					lo = mid
				} else {
					hi = mid - 1
				}
			}
			// Module headers and white space do not count towards a run's length.
			run := 0
			for j := i; j < i+lo; j++ {
				if keep[j] {
					run++
				}
			}
			if run > longest {
				longest = run
			}
			for d := range docsOf(sa, q[i:i+lo], docAt) {
				credit[d] += lo
			}
			i += lo
		}
		cand := make([]int, 0, len(credit))
		for d := range credit {
			cand = append(cand, d)
		}
		sort.Slice(cand, func(a, b int) bool {
			if credit[cand[a]] != credit[cand[b]] {
				return credit[cand[a]] > credit[cand[b]]
			}
			return docs[cand[a]].owners[0] < docs[cand[b]].owners[0]
		})
		if len(cand) > 40 {
			cand = cand[:40]
		}
		best, bestCov, ties := "", 0, 0
		for _, d := range cand {
			c := coverage(q, text[docs[d].start:docs[d].end], keep, k)
			if c > bestCov {
				best, bestCov, ties = docs[d].owners[0], c, 0
			} else if c == bestCov && c > 0 {
				ties++
			}
		}
		pct := 0.0
		if total > 0 {
			pct = 100 * float64(bestCov) / float64(total)
		}
		fmt.Fprintf(bw, "%s\t%d\t%d\t%d\t%s\t%d\t%.1f\t%d\n", it.ID, len(q)-len(it.Files), total, longest, best, bestCov, pct, ties)
	}
	return nil
}

func hasAny(sa *suffixarray.Index, b []byte) bool { return len(sa.Lookup(b, 1)) > 0 }

func docsOf(sa *suffixarray.Index, b []byte, docAt func(int) int) map[int]bool {
	out := map[int]bool{}
	for _, pos := range sa.Lookup(b, 20000) {
		out[docAt(pos)] = true
	}
	return out
}
