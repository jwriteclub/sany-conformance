// Guard classes. These are bytecode shapes, not proof: if (x != null) can be real
// logic. They feed separate numbers and never touch the reachability map.
const (
	GuardLogic      = "logic"
	GuardNull       = "null"
	GuardInstanceof = "instanceof"
	GuardAssert     = "assert"
	GuardThrow      = "throw-arm"
	GuardDefault    = "switch-default"
	GuardNtk        = "jj_ntk-cache"
	GuardScanToken  = "jj_scan_token"
	Guard3R         = "jj_3R"
	GuardScaffold   = "scaffold-class"
)

var guardOrder = []string{GuardNull, GuardInstanceof, GuardAssert, GuardThrow, GuardDefault, GuardNtk, GuardScanToken, Guard3R, GuardScaffold}

// scaffoldSources are the generated support classes with no grammar in them.
var scaffoldSources = map[string]bool{
	"ParseException.java": true, "SimpleCharStream.java": true, "Token.java": true,
	"TokenMgrError.java": true, "TLAplusParserConstants.java": true,
}

// generatedSources is the generated classes, by Generated By header.
var generatedSources = map[string]bool{
	"TLAplusParser.java": true, "TLAplusParserTokenManager.java": true, "TLAplusParserConstants.java": true,
	"ParseException.java": true, "SimpleCharStream.java": true, "Token.java": true, "TokenMgrError.java": true,
}

// IsGenerated says that a class comes from JavaCC.
func IsGenerated(c *Class) bool {
	return strings.HasPrefix(c.Name, "tla2sany/parser/") && generatedSources[c.SourceFile]
}

// ProbeRow is one line of BranchProbes output.
type ProbeRow struct {
	Key     string // method key
	Ordinal int
	Opcode  int
	Line    int
	Total   int
	Covered uint64 // arm bits; arms beyond 63 are held in Extra
	Extra   map[int]bool
}

// HitCount is the number of covered arms.
func (p *ProbeRow) HitCount() int { return len(p.Arms()) }

// Arms lists the covered arm numbers.
func (p *ProbeRow) Arms() []int {
	var out []int
	for i := 0; i < 64; i++ {
		if p.Covered&(1<<uint(i)) != 0 {
			out = append(out, i)
		}
	}
	for i := range p.Extra {
		out = append(out, i)
	}
	sort.Ints(out)
	return out
}

// Has says that an arm was covered.
func (p *ProbeRow) Has(arm int) bool {
	if arm < 64 {
		return p.Covered&(1<<uint(arm)) != 0
	}
	return p.Extra[arm]
}

// ProbeTable is the per-instruction data of one exec file, by method key.
type ProbeTable map[string][]*ProbeRow

// ReadProbes reads the helper's output.
func ReadProbes(path string) (ProbeTable, error) {
	f, err := openData(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	out := ProbeTable{}
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 0, 1<<16), 1<<22)
	for sc.Scan() {
		w := strings.Split(sc.Text(), "\t")
		if len(w) != 8 {
			return nil, fmt.Errorf("%s: bad row %q", path, sc.Text())
		}
		r := &ProbeRow{Key: w[0] + "." + w[1] + ":" + w[2]}
		fields := []*int{&r.Ordinal, &r.Opcode, &r.Line, &r.Total}
		for i, p := range fields {
			if *p, err = strconv.Atoi(w[3+i]); err != nil {
				return nil, fmt.Errorf("%s: bad row %q", path, sc.Text())
			}
		}
		if w[7] != "-" {
			for _, a := range strings.Split(w[7], ",") {
				arm, err := strconv.Atoi(a)
				if err != nil {
					return nil, fmt.Errorf("%s: bad row %q", path, sc.Text())
				}
				if arm < 64 {
					r.Covered |= 1 << uint(arm)
				} else {
					if r.Extra == nil {
						r.Extra = map[int]bool{}
					}
					r.Extra[arm] = true
				}
			}
		}
		out[r.Key] = append(out[r.Key], r)
	}
	return out, sc.Err()
}

// CheckAgainst fails unless the per-instruction data sums to JaCoCo's own method counters.
func (t ProbeTable) CheckAgainst(cov *Coverage) error {
	for _, k := range sortedKeys(cov) {
		mc := cov.Methods[k]
		total, hit := 0, 0
		for _, r := range t[k] {
			total += r.Total
			hit += r.HitCount()
		}
		if total != mc.BranchTotal || hit != mc.BranchHit {
			return fmt.Errorf("%s: probes say %d of %d, %s says %d of %d", k, hit, total, cov.Path, mc.BranchHit, mc.BranchTotal)
		}
	}
	return nil
}

// BranchShape classifies one branch instruction from the class file alone.
type BranchShape struct {
	Off    int
	Line   int
	Op     uint8
	Class  string
	Throw  [2]bool // for a conditional: arm 0 (fall through) or arm 1 (jump) reaches athrow
	Plain  bool    // arm numbers mean what the bytecode says (no JaCoCo replacement)
	Target []int
}

// Excludable says which missed arm of this instruction the shape covers.
func (s *BranchShape) Excludable(arm int) bool {
	switch s.Class {
	case GuardLogic:
		return false
	case GuardAssert, GuardThrow:
		return s.Plain && arm < 2 && s.Throw[arm]
	case GuardDefault:
		return s.Plain && arm == 0
	}
	return true
}

// ArmName is a stable name for an arm, for the branch table.
func (s *BranchShape) ArmName(arm int) string {
	if !s.Plain {
		return "arm" + strconv.Itoa(arm)
	}
	name := "fall"
	if arm == 1 {
		name = "jump"
	}
	if arm < 2 && s.Throw[arm] {
		return name + ":throw"
	}
	switch s.Class {
	case GuardNull:
		isNull := (s.Op == opIfnull) == (arm == 1)
		if isNull {
			return name + ":null"
		}
		return name + ":nonnull"
	case GuardInstanceof:
		isInst := (s.Op == opIfne) == (arm == 1)
		if isInst {
			return name + ":instance"
		}
		return name + ":notinstance"
	}
	return name
}

// ClassifyMethod shapes the branches of a method, by instruction ordinal.
func (w *World) ClassifyMethod(m *Method) (map[int]*BranchShape, error) {
	if s, ok := w.shapes[m]; ok {
		return s, nil
	}
	if w.shapes == nil {
		w.shapes = map[*Method]map[int]*BranchShape{}
	}
	insns, err := m.Decode()
	if err != nil {
		return nil, err
	}
	index := map[int]int{}
	for i, in := range insns {
		index[in.Off] = i
	}
	reachesThrow := func(start int) (bool, bool) {
		isAssert := false
		seen := map[int]bool{}
		for i := start; i >= 0 && i < len(insns) && !seen[i]; {
			seen[i] = true
			in := insns[i]
			switch {
			case in.Op == opAthrow:
				return true, isAssert
			case in.IsConditional() || in.IsSwitch():
				return false, false
			case in.Op >= opIreturn && in.Op <= opReturn:
				return false, false
			case in.Op == opGoto || in.Op == opGotoW:
				next, ok := index[in.Targets[0]]
				if !ok {
					return false, false
				}
				i = next
				continue
			case in.Op == opNew && m.Class.className(in.Index) == "java/lang/AssertionError":
				isAssert = true
			}
			i++
		}
		return false, false
	}
	out := map[int]*BranchShape{}
	gen := IsGenerated(m.Class)
	for i, in := range insns {
		if !in.IsConditional() && !in.IsSwitch() {
			continue
		}
		s := &BranchShape{Off: in.Off, Line: m.LineAt(in.Off), Op: in.Op, Class: GuardLogic, Plain: true, Target: in.Targets}
		out[i] = s
		var prev, prev2 *Insn
		if i > 0 {
			prev = &insns[i-1]
		}
		if i > 1 {
			prev2 = &insns[i-2]
		}
		if in.IsSwitch() {
			if len(in.Targets) > 1 {
				s.Class = GuardDefault
			}
			if gen && scaffoldSources[m.Class.SourceFile] {
				s.Class = GuardScaffold
			}
			continue
		}
		fallThrow, fallAssert := reachesThrow(i + 1)
		jumpIdx, ok := index[in.Targets[0]]
		jumpThrow, jumpAssert := false, false
		if ok {
			jumpThrow, jumpAssert = reachesThrow(jumpIdx)
		}
		s.Throw = [2]bool{fallThrow, jumpThrow}
		switch {
		case isAssertionsDisabled(m, prev):
			s.Class = GuardAssert
		case fallAssert || jumpAssert:
			s.Class = GuardAssert
		case gen && scaffoldSources[m.Class.SourceFile]:
			s.Class = GuardScaffold
		case gen && isNtkCache(m, prev, prev2):
			s.Class = GuardNtk
		case gen && calls(m, prev, "jj_scan_token"):
			s.Class = GuardScanToken
		case gen && (strings.HasPrefix(m.Name, "jj_3R_") || strings.HasPrefix(m.Name, "jj_3_")):
			s.Class = Guard3R
		case in.Op == opIfnull || in.Op == opIfnonnull:
			s.Class = GuardNull
		case prev != nil && prev.Op == 193 && (in.Op == opIfeq || in.Op == opIfne): // instanceof
			s.Class = GuardInstanceof
		case fallThrow || jumpThrow:
			s.Class = GuardThrow
		}
	}
	w.shapes[m] = out
	return out, nil
}

func isAssertionsDisabled(m *Method, prev *Insn) bool {
	return prev != nil && prev.Op == opGetstatic && m.Class.memberRef(prev.Index).Name == "$assertionsDisabled"
}

func isNtkCache(m *Method, prev, prev2 *Insn) bool {
	return prev != nil && prev2 != nil && prev.Op == opIconstM1 && prev2.Op == opGetfield && m.Class.memberRef(prev2.Index).Name == "jj_ntk"
}

func calls(m *Method, prev *Insn, name string) bool {
	if prev == nil || prev.Op < opInvokevirt || prev.Op > opInvokeifc {
		return false
	}
	return m.Class.memberRef(prev.Index).Name == name
}

// GuardMissed counts the excludable missed arms of a method under one report.
type GuardMissed struct {
	Partly int // on an instruction with another arm hit
	Never  int // on an instruction with no arm hit
}

// Add folds another count in.
func (g *GuardMissed) Add(o GuardMissed) {
	g.Partly += o.Partly
	g.Never += o.Never
}

// MethodGuards works out one method's excludable missed arms, with a per-class breakdown.
func (w *World) MethodGuards(m *Method, rows []*ProbeRow, byClass map[string]*GuardTally) (GuardMissed, error) {
	var out GuardMissed
	if len(rows) == 0 {
		return out, nil
	}
	shapes, err := w.ClassifyMethod(m)
	if err != nil {
		return out, err
	}
	insns, _ := m.Decode()
	for _, r := range rows {
		s := shapes[r.Ordinal]
		if s == nil || r.Ordinal >= len(insns) || int(insns[r.Ordinal].Op) != r.Opcode {
			return out, fmt.Errorf("%s: JaCoCo's instruction %d (opcode %d) does not line up with the class file", m.Key(), r.Ordinal, r.Opcode)
		}
		// A JaCoCo filter can renumber arms; then the bytecode cannot name them.
		s.Plain = r.Total == conditionalOutcomes(insns[r.Ordinal])
		hit := r.HitCount()
		t := byClass[s.Class]
		if t == nil {
			t = &GuardTally{}
			byClass[s.Class] = t
		}
		t.Total += r.Total
		t.Hit += hit
		count := func(n int) {
			if hit > 0 {
				out.Partly += n
				t.Excl.Partly += n
			} else {
				out.Never += n
				t.Excl.Never += n
			}
		}
		if insns[r.Ordinal].IsSwitch() {
			// JaCoCo numbers a switch's arms by label position, or skipping duplicate
			// labels, depending on probe placement; only arm 0, the default, is stable.
			other := r.Total - hit
			if !r.Has(0) {
				other--
				if s.Excludable(0) {
					count(1)
				}
			}
			if other > 0 && s.Excludable(1) {
				count(other)
			}
			continue
		}
		for arm := 0; arm < r.Total; arm++ {
			if !r.Has(arm) && s.Excludable(arm) {
				count(1)
			}
		}
	}
	return out, nil
}

// GuardTally summarises one shape.
type GuardTally struct {
	Total int
	Hit   int
	Excl  GuardMissed
}
