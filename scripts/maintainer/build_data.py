HEAD = "# Copyright 2026 Christopher O'Connell\n# SPDX-License-Identifier: Apache-2.0\n"


def load_run(path):
    out = {}
    env = None
    opener = gzip.open if path.endswith(".gz") else open
    with opener(path, "rt", encoding="utf-8") as f:
        for line in f:
            r = json.loads(line)
            if "environment" in r:
                env = r["environment"]
            else:
                out[r["id"]] = r
    return env, out


RE_Q = re.compile("['\"`][^'\"`]*['\"`]")
RE_D = re.compile(r"[0-9]+")
RE_I = re.compile(r"\b[A-Z][A-Za-z0-9_]*\b")


def tlx_norm(s):
    if s.startswith("tlx: "):
        s = s[5:]
    s = RE_I.sub("X", RE_D.sub("N", RE_Q.sub("_", s)))
    s = re.sub(r"[\t\r\n]+", " ", s)
    return s[:80]


def load_verify(repo):
    path = os.path.join(repo, "scripts", "verify")
    loader = importlib.machinery.SourceFileLoader("verify", path)
    spec = importlib.util.spec_from_loader("verify", loader)
    m = importlib.util.module_from_spec(spec)
    loader.exec_module(m)
    return m


def crash_sig(V, o):
    """Exception, the frame that threw, and the message with its numbers blanked."""
    c = V.crash_of(o.get("stdout", ""), o.get("stderr", ""))
    msg = re.sub(r"^(Exception in thread \"main\" |tla2sany\.drivers\.FrontEndException: )", "", c["line"])
    return "crash %s@%s: %s" % (c["exception"], c["frame"], RE_D.sub("N", msg)[:100])


def main():
    ap = argparse.ArgumentParser()
    for name in ("repo", "cases", "runs", "kills", "tlx", "trace", "baseline"):
        ap.add_argument("--" + name, required=True)
    a = ap.parse_args()
    sys.dont_write_bytecode = True
    V = load_verify(a.repo)
    cases = [json.loads(l) for l in open(a.cases)]
    _, r1 = load_run(a.runs + "/r1.jsonl")
    h = {}
    for line in open(a.runs + "/harness.jsonl"):
        r = json.loads(line)
        h[r["id"]] = r
    tlx = {}
    for line in open(a.tlx):
        r = json.loads(line)
        tlx[r["id"]] = r
    data = a.repo + "/data"
    rows = set()
    combos = tlxs = crashes = 0
    for c in cases:
        i = c["ID"]
        o, hr = r1[i], h[i]
        if o["status"] == "ok" and hr["status"] == "ok":
            e = ",".join(map(str, hr["error_codes"]))
            w = ",".join(map(str, hr["warning_codes"]))
            rows.add((i, "combo %s|e=%s|w=%s" % (o["verdict"], e, w)))
            t = tlx[i]
            if t["tlx"] in ("accept", "reject") and t["tlx"] != o["verdict"]:
                code = hr["error_codes"][0] if hr["error_codes"] else ""
                rows.add((i, "tlx java=%s tlx=%s code=%s msg=%s" % (o["verdict"], t["tlx"], code, tlx_norm(t["msg"]))))
        if o["status"] == "crash":
            rows.add((i, crash_sig(V, o)))
        if (hr.get("semantic_graph_state") or "").startswith("crash:"):
            rows.add((i, "crash xml-export " + RE_D.sub("N", hr["semantic_graph_state"][6:])[:120]))
    primary = collections.defaultdict(set)
    wide = collections.defaultdict(set)
    with open(a.kills) as f:
        for l in f:
            if l.startswith("#") or l.startswith("mutant\t"):
                continue
            k, cid, run, kind = l.rstrip("\n").split("\t")
            (primary if kind == "primary" else wide)[k].add(cid)
    for k, ids in primary.items():
        for i in ids:
            rows.add((i, "mutant " + k))
    for k, ids in wide.items():
        if k not in primary:
            for i in ids:
                rows.add((i, "mutant-wide " + k))
    with open(data + "/elements-extra.tsv", "w") as f:
        f.write(HEAD + "# Generated by scripts/maintainer/build_data.py. case<TAB>element.\n")
        for r in sorted(rows):
            f.write("%s\t%s\n" % r)
    c = collections.Counter(e.split(" ", 1)[0] for _, e in rows)
    print("extra elements rows", dict(c), "distinct", len({e for _, e in rows}))
    with open(a.kills, "rb") as f, gzip.GzipFile(data + "/mutant-kills.tsv.gz", "wb", 9, mtime=0) as g:
        g.write(f.read())
    # Evidence: stated purpose, not measured coverage.
    ev = {}
    gaps = open(a.baseline + "/reference/grammar-gaps.md", encoding="utf-8").read()
    table = {}
    for m in re.finditer(r"^\| ([A-Za-z]+:\d+) \| ([^|]+?) \| `(\w+)` \|", gaps, re.M):
        table[m.group(3)] = "%s, outcome %s" % (m.group(1), m.group(2))
    for c in cases:
        i, o = c["ID"], c["Origin"]
        name = os.path.basename(o)[:-4] if o.endswith(".tla") else ""
        if c["Group"] == "model-openstart":
            ev[i] = "one of the modules written for the eight alternatives of the OpenStart lookahead scan, run to confirm that OpenStart() itself is never called and the scan is reached; nothing JaCoCo can credit"
        elif "hand-specs/grammar/La" in o:
            ev[i] = "hits a lookahead outcome JaCoCo cannot record, since its probe follows a call that throws: %s; shown by the patched parser trace" % table.get(name, name)
        elif "hand-specs/openstart/Below" in o:
            ev[i] = "a token at its bullet's column, the lookahead scan true and the column predicate false; JaCoCo cannot record it; shown by the patched parser trace"
        elif "hand-specs/outside-gate/" in o:
            ev[i] = "reaches comment-joining arms in SyntaxTreeNode only under XMLExporter -u, which no coverage pass here runs"
        elif i in ("D-5ac9249fe910", "D-f82fa4953e79"):
            ev[i] = "imports a standard module under a different case: shows how SANY depends on the file system; see FINDINGS.md"
    extra_ev = a.runs + "/evidence-extra.tsv"
    if os.path.exists(extra_ev):
        for l in open(extra_ev):
            i, why = l.rstrip("\n").split("\t", 1)
            ev.setdefault(i, why)
    with open(data + "/evidence.tsv", "w") as f:
        f.write(HEAD + "# Cases kept for a stated purpose that coverage cannot measure. case<TAB>purpose.\n")
        for i in sorted(ev):
            f.write("%s\t%s\n" % (i, ev[i]))
    print("evidence", len(ev))
    # How close each fuzz output is to anything the runs were seeded with. Provenance
    # only: the set's licence is at set level and does not rest on this.
    trace = {}
    for r in csv.DictReader((l for l in open(a.trace) if not l.startswith("#")), delimiter="\t"):
        trace[r["id"]] = r
    dictionary = read_dictionary(data + "/fuzz-dictionary.txt")
    methods = collections.Counter()
    with open(data + "/fuzz-trace.tsv", "w") as ft:
        ft.write(HEAD + "# Generated by scripts/maintainer/build_data.py. Provenance, not a licence claim: libFuzzer records no parent, so this is the corpus or model file closest to each fuzz output by content (cmd/tracecases), or the fuzzer's dictionary if the output holds only its tokens, numbers and short names, or nothing close.\nid\tclosest\tparent\tlongest_run\tcovered_pct\n")
        for c in cases:
            if c["Group"] != "fuzz-jazzer":
                continue
            t = trace[c["ID"]]
            if traced(t):
                method, parent = "corpus", t["best_parent"]
            elif only_dictionary(b"".join(open(os.path.join(c["Dir"], n), "rb").read() for n in c["Files"]), dictionary):
                method, parent = "dictionary", "tla+.jj"
            else:
                method, parent = "none", ""
            methods[method] += 1
            ft.write("%s\t%s\t%s\t%s\t%s\n" % (c["ID"], method, parent, t["longest_run"], t["covered_pct"]))
    print("closest match of fuzz outputs", dict(methods))


def read_dictionary(path):
    """The fuzzer's dictionary: tokens generated from tla+.jj."""
    out = set()
    for line in open(path, encoding="utf-8", errors="replace"):
        m = re.match(r't\d+="(.*)"$', line.strip())
        if m:
            t = re.sub(r"\\x([0-9a-fA-F]{2})", lambda x: chr(int(x.group(1), 16)), m.group(1)).replace("\\\\", "\\").replace('\\"', '"')
            t = t.encode("latin1", "replace").strip()
            if t:
                out.add(t)
    return sorted(out, key=lambda x: (-len(x), x))


RE_WORD = re.compile(rb"[A-Za-z0-9_]+")


def only_dictionary(b, dictionary):
    """Every byte is white space, a dictionary token, a number, or a name of at most 8
    characters. Such a file holds nothing to trace beyond the grammar's own tokens."""
    pos = 0
    while pos < len(b):
        if b[pos:pos + 1] in (b" ", b"\t", b"\r", b"\n"):
            pos += 1
            continue
        for t in dictionary:
            if b.startswith(t, pos):
                pos += len(t)
                break
        else:
            m = RE_WORD.match(b, pos)
            if not m or (len(m.group(0)) > 8 and not m.group(0).isdigit()):
                return False
            pos = m.end()
    return True


def traced(t):
    """A fuzz output is close to a file if it shares 32 contiguous bytes with one corpus
    file, or that file covers half of its measured bytes in runs of 16 or more."""
    return bool(t["best_parent"]) and (int(t["longest_run"]) >= 32 or (int(t["longest_run"]) >= 16 and float(t["covered_pct"]) >= 50))


if __name__ == "__main__":
    main()
