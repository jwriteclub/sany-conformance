"""Make data/ from the stock runs: what each case can be the reason for.

One-time, for a maintainer holding the measurement's outputs; nothing a reader runs
needs this. Writes data/elements-extra.tsv, data/evidence.tsv, data/fuzz-trace.tsv
and data/mutant-kills.tsv.gz.

usage: build_data.py --repo R --cases cases.json --runs DIR --kills mutant-kills.tsv
                     --tlx tlx.jsonl --trace trace.tsv --baseline B
"""
