"""Measure what the Jazzer runs were fed, from the directories the runs used.

One-time, for a maintainer holding the fuzz tree. Writes data/fuzz-seeds.tsv, one row per
seed the runs were given, and data/fuzz-seed-sources.json, the totals LICENSE.md quotes.

usage: fuzz_seeds.py --repo R --cases cases.json --fuzz .tools/climb/fuzz.noindex --baseline B
"""
import argparse
import collections
import csv
import glob
import json
import os
import re


def main():
    ap = argparse.ArgumentParser()
    for name in ("repo", "cases", "fuzz", "baseline"):
        ap.add_argument("--" + name, required=True)
    a = ap.parse_args()
    cases = {c["ID"]: c for c in map(json.loads, open(a.cases))}
    lic = {}
    for p in glob.glob(a.baseline + "/suite/*/cases.tsv"):
        with open(p, newline="", encoding="utf-8", errors="replace") as f:
            lines = [l for l in f if not l.startswith("#")]
        for r in csv.DictReader(lines, delimiter="\t", quoting=csv.QUOTE_NONE):
            lic[r["id"]] = r["licence"]
    strategies = collections.defaultdict(set)
    for d in sorted(glob.glob(a.fuzz + "/seeds/*")):
        for n in os.listdir(d):
            if n.endswith(".tla"):
                strategies[n[:-4]].add(os.path.basename(d))
    rows = []
    table = collections.Counter()
    for i in sorted(strategies):
        c = cases[i]
        m = re.match(r"^(?:derivative of \S+: )?(\S+) \((.+)\)$", lic.get(i, ""))
        if m:
            spdx, file = m.groups()
            kind = "mutant of" if c["Tier"] == "C" else "file from"
        else:
            spdx, file, kind = "Apache-2.0", "LICENSE", "model spec"
        table[(file, spdx, kind)] += 1
        rows.append((i, ",".join(sorted(strategies[i])), kind, file, spdx))
    with open(a.repo + "/data/fuzz-seeds.tsv", "w") as f:
        f.write("# Copyright 2026 Christopher O'Connell\n# SPDX-License-Identifier: Apache-2.0\n# Generated by scripts/maintainer/fuzz_seeds.py. Every case the Jazzer strategies were seeded with.\nid\tstrategies\tkind\tlicence_file\tspdx\n")
        for r in rows:
            f.write("\t".join(r) + "\n")
    # Everything else the runs read, and a search of all of it for the unlicensed upstream.
    rx = re.compile(rb"(?i)paxosstore|tpaxos|tlx_participant")
    other = {}
    for name in ("seeds", "kept-seeds", "model-near", "retained"):
        n = hits = 0
        for root, _, fs in os.walk(os.path.join(a.fuzz, name)):
            for fn in fs:
                if fn == ".done":
                    continue
                n += 1
                with open(os.path.join(root, fn), "rb") as f:
                    if rx.search(f.read()):
                        hits += 1
        other[name] = {"files": n, "mention_paxosstore": hits}
    kept = collections.Counter()
    for fn in os.listdir(os.path.join(a.fuzz, "kept-seeds")):
        i = fn[:-4]
        kept[cases[i]["Group"] if i in cases else "not in the suite"] += 1
    external = sum(1 for i in strategies if "corpus/external/" in cases[i]["Origin"])
    out = {"copyright": "Copyright 2026 Christopher O'Connell", "spdx": "Apache-2.0", "distinct_seeds": len(strategies), "seed_table": [list(k) + [v] for k, v in sorted(table.items())], "tlx_corpus_external_seeds": external, "other_inputs": other, "kept_seeds_by_set": kept}
    with open(a.repo + "/data/fuzz-seed-sources.json", "w") as f:
        json.dump(out, f, indent=1, sort_keys=True)
        f.write("\n")
    for k, v in sorted(table.items()):
        print(v, k)
    print(json.dumps({k: out[k] for k in ("distinct_seeds", "tlx_corpus_external_seeds", "other_inputs", "kept_seeds_by_set")}))


if __name__ == "__main__":
    main()
